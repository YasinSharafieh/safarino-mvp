const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on('pageerror', e => errors.push('JS ' + e.message.slice(0, 80)));
  await page.goto('https://safarino-mvp.vercel.app/itinerary?city=' + encodeURIComponent('شیراز') + '&days=2', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(17000);
  console.log('scrollWidth:', await page.evaluate(() => document.documentElement.scrollWidth));
  const text = await page.innerText('body');
  console.log('has map:', text.includes('نقشهٔ روز'));
  console.log('nav buttons:', (await page.$$('button:has-text("مسیریابی با نشان")')).length);
  await page.screenshot({ path: '/home/user/itinerary-mobile.png', fullPage: false });
  await page.goto('https://safarino-mvp.vercel.app/itinerary/print', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(9000);
  console.log('print scrollWidth:', await page.evaluate(() => document.documentElement.scrollWidth));
  await page.screenshot({ path: '/home/user/itinerary-print-mobile.png' });
  console.log('errors:', errors.slice(0, 3));
  await browser.close();
})();
